PHASE_ORDER = ["loading", "start", "stop", "unloading"]


def phase_of_step(step_id: str) -> str:
    return STEPS_BY_ID[step_id]["phase"]


def steps_of_phase(phase: str):
    return [s for s in STEPS if s["phase"] == phase]


def first_step_of_phase(phase: str) -> str:
    return steps_of_phase(phase)[0]["id"]


def is_last_step_of_phase(step_id: str) -> bool:
    steps = steps_of_phase(STEPS_BY_ID[step_id]["phase"])
    return steps[-1]["id"] == step_id


def next_step_id(step_id: str):
    idx = STEP_ORDER.index(step_id)
    if idx + 1 < len(STEP_ORDER):
        return STEP_ORDER[idx + 1]
    return None


